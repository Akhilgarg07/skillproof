"""Markdown report: for PR comments, READMEs and issue threads."""

from __future__ import annotations

from skilltest.report.format import (
    VERDICT_TEXT,
    fraction,
    interval,
    seconds,
    signed_pct,
    summary_line,
    tokens,
    usd,
)
from skilltest.report.summary import Summary

VERDICT_EMOJI = {
    "helps": "✅",
    "hurts": "❌",
    "no clear effect": "➖",
    "too few runs": "➖",
    "not measured": "➖",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(s: Summary) -> str:
    lines = [f"## skilltest: `{s.skill_name}`", ""]
    lines.append(f"**{VERDICT_EMOJI[s.verdict]} {VERDICT_TEXT[s.verdict]}**  ")
    lines.append(f"`{summary_line(s)}`")
    lines.append("")
    meta = f"runner `{s.runner}`"
    if s.model:
        meta += f" · model `{s.model}`"
    if s.judge:
        meta += f" · judge `{s.judge}`"
    if s.approximate:
        meta += " · **approximate**"
    lines += [meta, ""]

    lines.append(
        "| case | triggered | pass with | pass without | lift (95% CI) | tokens Δ | latency Δ |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|---:|")
    for c in s.cases:
        w, wo = c.with_skill, c.without_skill
        trig = fraction(w.triggered, w.trigger_known)
        if not c.should_trigger:
            trig += " (should not)"
        if c.has_assertions:
            lift = f"{signed_pct(c.lift)} ({interval(c.lift_ci)})"
            pw, pwo = fraction(w.passed, w.runs), fraction(wo.passed, wo.runs)
        else:
            lift, pw, pwo = "–", "–", "–"
        lines.append(
            f"| {_cell(c.name)} | {trig} | {pw} | {pwo} | {lift} | "
            f"{signed_pct(c.token_delta)} | {signed_pct(c.latency_delta)} |"
        )
    lines.append("")

    w, wo = s.with_skill, s.without_skill
    lines.append("| | with skill | without |")
    lines.append("|---|---:|---:|")
    lines.append(f"| pass rate | {fraction(w.passed, w.runs)} | {fraction(wo.passed, wo.runs)} |")
    lines.append(f"| tokens / run | {tokens(w.mean_tokens)} | {tokens(wo.mean_tokens)} |")
    if w.mean_cost_usd is not None or wo.mean_cost_usd is not None:
        lines.append(f"| cost / run | {usd(w.mean_cost_usd)} | {usd(wo.mean_cost_usd)} |")
    lines.append(f"| time / run | {seconds(w.mean_duration_s)} | {seconds(wo.mean_duration_s)} |")
    lines.append("")

    if s.notes:
        lines += [f"> {note}  " for note in s.notes]
        lines.append("")
    lines.append("<sub>Generated by [skilltest](https://github.com/akhilgarg07/skilltest)</sub>")
    return "\n".join(lines) + "\n"
